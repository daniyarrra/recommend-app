-- Этот скрипт откроет доступ к чтению профилей для всех пользователей.
-- Это нужно, чтобы в списке подписчиков и уведомлениях отображались никнеймы, а не "Скрытый пользователь".

-- 1. Удаляем старую политику, если она есть (имя может отличаться, поэтому мы просто добавим новую разрешающую)
-- Включаем RLS на всякий случай
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

-- 2. Создаем политику, которая разрешает ВСЕМ читать таблицу profiles
CREATE POLICY "Разрешить чтение профилей всем" 
ON public.profiles FOR SELECT 
USING (true);
